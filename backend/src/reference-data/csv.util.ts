/**
 * Minimal CSV parser for the reference datasets (GEN-12).
 * Handles a UTF-8 BOM, CRLF line endings, quoted fields, commas inside quotes
 * and doubled quotes ("") inside quoted fields. The first row is the header.
 * Blank lines are skipped.
 */
export function parseCsv(text: string): Record<string, string>[] {
  const input = text.charCodeAt(0) === 0xfeff ? text.slice(1) : text;
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let inQuotes = false;

  for (let i = 0; i < input.length; i++) {
    const ch = input[i];
    if (inQuotes) {
      if (ch === '"') {
        if (input[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += ch;
      }
      continue;
    }
    if (ch === '"') {
      inQuotes = true;
    } else if (ch === ',') {
      row.push(field);
      field = '';
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && input[i + 1] === '\n') i++;
      row.push(field);
      field = '';
      rows.push(row);
      row = [];
    } else {
      field += ch;
    }
  }
  if (field !== '' || row.length > 0) {
    row.push(field);
    rows.push(row);
  }

  const nonBlank = rows.filter((r) => r.some((cell) => cell.trim() !== ''));
  if (nonBlank.length === 0) return [];
  const headers = nonBlank[0].map((h) => h.trim());
  return nonBlank.slice(1).map((cells) => {
    const record: Record<string, string> = {};
    headers.forEach((header, index) => {
      record[header] = (cells[index] ?? '').trim();
    });
    return record;
  });
}
